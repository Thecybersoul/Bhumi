const ALL_STAGES: VerificationStageKey[] = [
  'intake',
  'title-chain',
  'revenue-zoning',
  'litigation',
  'physical',
  'report',
]

function stagesUpTo(reached: VerificationStageKey, flaggedAt?: VerificationStageKey) {
  const idx = ALL_STAGES.indexOf(reached)
  return ALL_STAGES.map((key, i) => ({
    key,
    status:
      flaggedAt === key
        ? ('Flagged' as const)
        : i < idx
          ? ('Verified' as const)
          : i === idx
            ? flaggedAt
              ? ('Not started' as const)
              : ('In progress' as const)
            : ('Not started' as const),
    reviewer: i <= idx ? 'Advisory desk' : '',
    note: '',
  }))
}

function completed(flaggedAt?: VerificationStageKey) {
  return ALL_STAGES.map((key) => ({
    key,
    status: flaggedAt === key ? ('Flagged' as const) : ('Verified' as const),
    reviewer: 'Advisory desk',
    note: '',
  }))
}

